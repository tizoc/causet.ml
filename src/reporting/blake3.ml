(* The compression function's arithmetic, on unboxed 64-bit integers: a
   word is the low 32 bits. The bits above them may hold anything: an
   addition or an exclusive or leaves the low 32 bits what they would be
   without them, and a rotation drops them before it shifts, so a word is
   masked only when it is stored. On [int]s each of these operations would
   also untag and retag. *)
module W = struct
  external ( + ) : int64 -> int64 -> int64 = "%int64_add"
  external ( lxor ) : int64 -> int64 -> int64 = "%int64_xor"
  external ( lor ) : int64 -> int64 -> int64 = "%int64_or"
  external ( land ) : int64 -> int64 -> int64 = "%int64_and"
  external ( lsl ) : int64 -> int -> int64 = "%int64_lsl"
  external ( lsr ) : int64 -> int -> int64 = "%int64_lsr"

  let mask64 = 0xffff_ffffL
  let[@inline] rotr16 x = ((x land mask64) lsr 16) lor (x lsl 16)
  let[@inline] rotr12 x = ((x land mask64) lsr 12) lor (x lsl 20)
  let[@inline] rotr8 x = ((x land mask64) lsr 8) lor (x lsl 24)
  let[@inline] rotr7 x = ((x land mask64) lsr 7) lor (x lsl 25)
  let[@inline] word a i = Int64.of_int (Array.unsafe_get a i)
  let[@inline] store a i x = Array.unsafe_set a i (Int64.to_int (x land mask64))
end

