(* BLAKE3, the 32-byte hash of an input, bit for bit the reference
   algorithm: the Rust port samples, dedupes and picks reservoir samples by
   it, so the two ports keep the same reports. Words are 32 bits held in
   OCaml ints.

   A hasher takes its input in pieces, as the reference's incremental
   hasher does: a block is compressed once it is full and more input comes,
   a chunk's chaining value is merged into the stack of finished subtrees
   once the chunk is full and more input comes, and [digest_into] compresses
   what is left. Nothing is allocated per byte, block or chunk: the stack
   grows only past a 2^k-chunk input it has not seen before. *)

