type t = {
  block : Bytes.t;  (** The block being filled. *)
  mutable fill : int;  (** Its bytes so far. *)
  mutable blocks_done : int;  (** The current chunk's blocks compressed so far. *)
  mutable chunk : int;  (** The current chunk's counter. *)
  cv : int array;  (** The current chunk's chaining value. *)
  m : int array;  (** Message words being compressed. *)
  out : int array;  (** The last compression's output. *)
  mutable stack : int array;
      (** Chaining values of finished subtrees, eight words each. *)
  mutable depth : int;  (** How many. *)
}

let create () =
  {
    block = Bytes.make block_len '\000';
    fill = 0;
    blocks_done = 0;
    chunk = 0;
    cv = Array.copy iv;
    m = Array.make 16 0;
    out = Array.make 8 0;
    stack = [||];
    depth = 0;
  }

let reset h =
  h.fill <- 0;
  h.blocks_done <- 0;
  h.chunk <- 0;
  Array.blit iv 0 h.cv 0 8;
  h.depth <- 0

(* The block's sixteen words into [m], its unfilled bytes zeroed first. *)
let load_block h =
  for i = h.fill to block_len - 1 do
    Bytes.unsafe_set h.block i '\000'
  done;
  for i = 0 to 7 do
    let w = get64u h.block (8 * i) in
    let w = if Sys.big_endian then bswap64 w else w in
    Array.unsafe_set h.m (2 * i) (Int64.to_int w land mask);
    Array.unsafe_set h.m ((2 * i) + 1) (Int64.to_int (Int64.shift_right_logical w 32))
  done

let[@inline] start_flag h = if h.blocks_done = 0 then chunk_start else 0

(* [out] made the parent of the top of the stack and itself, popping it. *)
let merge_top h =
  h.depth <- h.depth - 1;
  Array.blit h.stack (8 * h.depth) h.m 0 8;
  Array.blit h.out 0 h.m 8 8;
  compress h.m iv ~counter:0 ~len:block_len ~flags:parent h.out

(* Pushes [out], the chaining value of chunk [h.chunk], after merging every
   subtree it completes. *)
let push_chunk h =
  let chunks = ref (h.chunk + 1) in
  while !chunks land 1 = 0 do
    merge_top h;
    chunks := !chunks lsr 1
  done;
  if 8 * (h.depth + 1) > Array.length h.stack then (
    let stack = Array.make (Int.max 64 (2 * Array.length h.stack)) 0 in
    Array.blit h.stack 0 stack 0 (8 * h.depth);
    h.stack <- stack);
  Array.blit h.out 0 h.stack (8 * h.depth) 8;
  h.depth <- h.depth + 1

(* Compresses the full block, now that more input follows it: into the
   chunk's chaining value, or, as the chunk's last, into the stack. *)
let flush_block h =
  load_block h;
  if h.blocks_done = blocks_per_chunk - 1 then (
    compress h.m h.cv ~counter:h.chunk ~len:block_len
      ~flags:(start_flag h lor chunk_end)
      h.out;
    push_chunk h;
    h.chunk <- h.chunk + 1;
    h.blocks_done <- 0;
    Array.blit iv 0 h.cv 0 8)
  else (
    compress h.m h.cv ~counter:h.chunk ~len:block_len ~flags:(start_flag h) h.cv;
    h.blocks_done <- h.blocks_done + 1);
  h.fill <- 0

let[@inline] room h =
  if h.fill = block_len then flush_block h;
  block_len - h.fill

let add_char h c =
  ignore (room h);
  Bytes.unsafe_set h.block h.fill c;
  h.fill <- h.fill + 1

(* Unchecked: [off] and [len] are a valid range of [s], which the public
   entry points make sure of. *)
let rec add_range h s off len =
  if len > 0 then (
    let n = Int.min len (room h) in
    if n <= 16 then
      for i = 0 to n - 1 do
        Bytes.unsafe_set h.block (h.fill + i) (String.unsafe_get s (off + i))
      done
    else Bytes.blit_string s off h.block h.fill n;
    h.fill <- h.fill + n;
    add_range h s (off + n) (len - n))

let add_substring h s off len =
  if off < 0 || len < 0 || off > String.length s - len then
    invalid_arg "Blake3.add_substring";
  add_range h s off len

let add_string h s = add_range h s 0 (String.length s)

let add_int64_le h x =
  if room h >= 8 then (
    set64u h.block h.fill (if Sys.big_endian then bswap64 x else x);
    h.fill <- h.fill + 8)
  else
    for i = 0 to 7 do
      add_char h
        (Char.unsafe_chr (Int64.to_int (Int64.shift_right_logical x (8 * i)) land 0xff))
    done

let add_int_le h n = add_int64_le h (Int64.of_int n)
let add_float_bits_le h x = add_int64_le h (Int64.bits_of_float x)

(* The final chunk's last block, then the parents up the stack; the root's
   compression writes the hash. *)
let finish h =
  load_block h;
  let flags = start_flag h lor chunk_end in
  if h.depth = 0 then
    compress h.m h.cv ~counter:h.chunk ~len:h.fill ~flags:(flags lor root) h.out
  else (
    compress h.m h.cv ~counter:h.chunk ~len:h.fill ~flags h.out;
    while h.depth > 1 do
      merge_top h
    done;
    h.depth <- 0;
    Array.blit h.stack 0 h.m 0 8;
    Array.blit h.out 0 h.m 8 8;
    compress h.m iv ~counter:0 ~len:block_len ~flags:(parent lor root) h.out)

let digest_into h dst off =
  if off < 0 || off > Bytes.length dst - 32 then invalid_arg "Blake3.digest_into";
  finish h;
  for i = 0 to 7 do
    let w = Int32.of_int (Array.unsafe_get h.out i) in
    set32u dst (off + (4 * i)) (if Sys.big_endian then bswap32 w else w)
  done;
  reset h

let digest h =
  let b = Bytes.create 32 in
  digest_into h b 0;
  Bytes.unsafe_to_string b

(* The first eight bytes of the hash, little-endian, as Rust reads a [u64]
   of them. *)
let digest_u64_prefix h =
  finish h;
  reset h;
  Int64.logor
    (Int64.of_int (Array.unsafe_get h.out 0))
    (Int64.shift_left (Int64.of_int (Array.unsafe_get h.out 1)) 32)

let hash input =
  let h = create () in
  add_string h input;
  digest h

(* Its first eight bytes, little-endian, as Rust reads a [u64] of them. *)
let u64_prefix digest = String.get_int64_le digest 0

let to_hex digest =
  String.concat "" (List.init 32 (fun i -> Printf.sprintf "%02x" (Char.code digest.[i])))
